export const CATALOG_BY_ID=new Map(PRODUCT_CATALOG.map(product=>[product.id,product]));

export function hydrateMatches(ids,reasons={}){
  const matches=[];
  const seen=new Set();
  for(const id of ids||[]){
    if(seen.has(id)) continue;
    const product=CATALOG_BY_ID.get(id);
    if(!product) continue;
    seen.add(id);
    matches.push({...product,reason:typeof reasons[id]==='string'&&reasons[id].trim()?reasons[id].trim().slice(0,220):product.description});
    if(matches.length===3) break;
  }
  return matches;
}
